"""Temporary demo data and its database boundary. No real account data is copied."""
from datetime import timedelta
from pathlib import Path
import re
from uuid import UUID, uuid4

from psycopg import sql


class DemoExpired(Exception):
    pass


class DemoLimit(Exception):
    pass


def find_workspace(conn, workspace_id, lock=False):
    try:
        workspace_id = UUID(str(workspace_id))
    except (ValueError, TypeError, AttributeError):
        return None
    query = "SELECT * FROM demo_workspaces WHERE id = %s AND expires_at > CURRENT_TIMESTAMP"
    if lock:
        query += " FOR SHARE"
    return conn.execute(query, (workspace_id,)).fetchone()


def checked_schema(name):
    # Only names generated by this module can be selected or removed.
    if not re.fullmatch(r"examreg_demo_[0-9a-f]{32}", name):
        raise ValueError("Invalid demo workspace name")
    return sql.Identifier(name)


def bind_workspace(conn, workspace_id):
    workspace = find_workspace(conn, workspace_id, lock=True)
    if not workspace:
        conn.close()
        raise DemoExpired()
    # No fallback to regular tables: a missing demo table must fail closed.
    conn.execute(sql.SQL("SET LOCAL search_path TO {}").format(checked_schema(workspace["schema_name"])))


def lock_directory(conn):
    # Serialize creation/reset/cleanup, scoped to this installation's base schema.
    conn.execute("SELECT pg_advisory_xact_lock(hashtext(current_schema()), hashtext('examreg-demo-directory'))")


def cleanup_expired(conn):
    lock_directory(conn)
    expired = conn.execute(
        "SELECT id, schema_name FROM demo_workspaces WHERE expires_at <= CURRENT_TIMESTAMP FOR UPDATE SKIP LOCKED"
    ).fetchall()
    for workspace in expired:
        conn.execute(sql.SQL("DROP SCHEMA IF EXISTS {} CASCADE").format(checked_schema(workspace["schema_name"])))
        conn.execute("DELETE FROM demo_workspaces WHERE id = %s", (workspace["id"],))
    return len(expired)


def delete_workspace(conn, workspace_id):
    lock_directory(conn)
    workspace = conn.execute(
        "SELECT schema_name FROM demo_workspaces WHERE id = %s FOR UPDATE", (UUID(str(workspace_id)),)
    ).fetchone()
    if workspace:
        conn.execute(sql.SQL("DROP SCHEMA IF EXISTS {} CASCADE").format(checked_schema(workspace["schema_name"])))
        conn.execute("DELETE FROM demo_workspaces WHERE id = %s", (UUID(str(workspace_id)),))


def create_workspace(conn, password_hash, max_workspaces=20):
    cleanup_expired(conn)
    if conn.execute("SELECT COUNT(*) AS count FROM demo_workspaces").fetchone()["count"] >= max_workspaces:
        raise DemoLimit()
    workspace_id = uuid4()
    schema_name = "examreg_demo_" + workspace_id.hex
    base_schema = conn.execute("SELECT current_schema() AS name").fetchone()["name"]
    conn.execute(sql.SQL("CREATE SCHEMA {}").format(checked_schema(schema_name)))
    conn.execute(sql.SQL("SET LOCAL search_path TO {}").format(checked_schema(schema_name)))
    conn.execute(Path(__file__).with_name("schema.sql").read_text(encoding="utf-8"))

    def user(email, name, role, nshe=None):
        return conn.execute(
            "INSERT INTO users (email,full_name,role,nshe,password_hash) VALUES (%s,%s,%s,%s,%s) RETURNING id",
            (email, name, role, nshe, password_hash),
        ).fetchone()["id"]

    faculty = user("faculty@demo.invalid", "Demo Faculty", "faculty")
    student = user("student@demo.invalid", "Demo Student", "student", "0000000001")
    peer = user("classmate@demo.invalid", "Demo Classmate", "student", "0000000002")
    location = conn.execute(
        """INSERT INTO locations (campus_name,building_name,room_number)
           VALUES ('Henderson','Demo Learning Center','101') RETURNING id"""
    ).fetchone()["id"]
    now = conn.execute("SELECT LOCALTIMESTAMP AS now").fetchone()["now"]
    session_ids = []
    # Relative dates keep the demo useful without manually updating old sessions.
    for index, (code, days, capacity) in enumerate((
        ("DEMO-CS101", 1, 20), ("DEMO-MATH120", 2, 12),
        ("DEMO-ENG101", 3, 1), ("DEMO-BIO100", 4, 15),
        ("DEMO-HIST101", -2, 20),
    )):
        exam = conn.execute(
            "INSERT INTO exams (exam_code,description) VALUES (%s,%s) RETURNING id",
            (code, "Fictional sample exam " + str(index + 1)),
        ).fetchone()["id"]
        exam_session = conn.execute(
            """INSERT INTO examsessions (exam_id,location_id,creator_id,proctor_id,session_datetime,capacity)
               VALUES (%s,%s,%s,%s,%s,%s) RETURNING id""",
            (exam, location, faculty, faculty, now + timedelta(days=days), capacity),
        ).fetchone()["id"]
        session_ids.append(exam_session)
    # Show an upcoming appointment, a full exam, a cancelled booking and history.
    for exam_session, user_id, cancelled in (
        (session_ids[0], student, False), (session_ids[2], peer, False),
        (session_ids[3], student, True), (session_ids[4], student, False),
    ):
        conn.execute(
            """INSERT INTO registrations (session_id,user_id,cancelled,cancelled_at)
               VALUES (%s,%s,%s,%s)""",
            (exam_session, user_id, cancelled, now if cancelled else None),
        )
    # Return to the base schema before writing the workspace directory entry.
    conn.execute(sql.SQL("SET LOCAL search_path TO {}").format(sql.Identifier(base_schema)))
    return conn.execute(
        """INSERT INTO demo_workspaces (id,schema_name,student_id,faculty_id,expires_at)
           VALUES (%s,%s,%s,%s,CURRENT_TIMESTAMP + INTERVAL '2 hours') RETURNING *""",
        (workspace_id, schema_name, student, faculty),
    ).fetchone()
