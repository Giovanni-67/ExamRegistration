-- Run against an existing PostgreSQL database using `flask --app app init-db`.
-- Re-running preserves existing records and creates missing tables and indexes.
CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(255) UNIQUE NOT NULL,
  nshe VARCHAR(10) UNIQUE,
  full_name VARCHAR(255) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  role VARCHAR(10) NOT NULL DEFAULT 'student' CHECK (role IN ('student', 'faculty')),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);


-- EXAMS TABLE
CREATE TABLE IF NOT EXISTS exams (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  exam_code VARCHAR(255) UNIQUE NOT NULL,
  description VARCHAR(255)
);

-- LOCATIONS TABLE
CREATE TABLE IF NOT EXISTS locations (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campus_name VARCHAR(50) NOT NULL CHECK (campus_name IN ('Henderson', 'Charleston', 'North Las Vegas')),
  building_name VARCHAR(255) NOT NULL,
  room_number VARCHAR(50) NOT NULL
);

-- EXAM SESSIONS TABLE
CREATE TABLE IF NOT EXISTS examsessions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  exam_id INT NOT NULL,
  session_datetime TIMESTAMP NOT NULL,
  location_id INT NOT NULL,
  creator_id INT NOT NULL,
  proctor_id INT NOT NULL,
  duration_minutes INT NOT NULL DEFAULT 90 CHECK (duration_minutes > 0),
  capacity INT NOT NULL DEFAULT 20 CHECK (capacity > 0),
  FOREIGN KEY (exam_id) REFERENCES exams(id),
  FOREIGN KEY (location_id) REFERENCES locations(id),
  FOREIGN KEY (creator_id) REFERENCES users(id),
  FOREIGN KEY (proctor_id) REFERENCES users(id)
);

-- REGISTRATIONS TABLE
CREATE TABLE IF NOT EXISTS registrations (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id INT NOT NULL,
  user_id INT NOT NULL,
  registered_at TIMESTAMP DEFAULT NOW(),
  cancelled BOOLEAN NOT NULL DEFAULT FALSE,
  cancelled_at TIMESTAMP NULL,
  UNIQUE (user_id, session_id),
  FOREIGN KEY (user_id) REFERENCES users(id),
  FOREIGN KEY (session_id) REFERENCES examsessions(id)
);

CREATE TABLE IF NOT EXISTS appointments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INT NOT NULL,
  title VARCHAR(200) NOT NULL,
  starts_at TIMESTAMP NOT NULL,
  ends_at TIMESTAMP NOT NULL,
  location VARCHAR(200) DEFAULT NULL,
  notes TEXT DEFAULT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_appt_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

-- PostgreSQL does not automatically index foreign keys.
-- The registration UNIQUE constraint already indexes user_id first.
CREATE INDEX IF NOT EXISTS idx_registrations_session ON registrations (session_id);
CREATE INDEX IF NOT EXISTS idx_sessions_datetime ON examsessions (session_datetime);
CREATE INDEX IF NOT EXISTS idx_sessions_exam ON examsessions (exam_id);
CREATE INDEX IF NOT EXISTS idx_sessions_location ON examsessions (location_id);
CREATE INDEX IF NOT EXISTS idx_sessions_creator ON examsessions (creator_id);
CREATE INDEX IF NOT EXISTS idx_sessions_proctor ON examsessions (proctor_id);
CREATE INDEX IF NOT EXISTS idx_user_time ON appointments (user_id, starts_at);
